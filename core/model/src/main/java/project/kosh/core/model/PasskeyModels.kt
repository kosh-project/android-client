package project.kosh.core.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/**
 * Challenge response payload returned by passkey ceremony initiation endpoints:
 * - `POST /api/auth/passkey/login/start` (discoverable login)
 * - `POST /api/v1/auth/passkey/register/start` (authenticated passkey enrollment)
 *
 * @property challengeId Ephemeral UUID correlating the start ceremony with subsequent finish verification.
 * @property challenge Raw WebAuthn challenge parameters generated by the server relying party.
 */
@Serializable
data class PasskeyChallengeResponse(
    @SerialName("challenge_id")
    val challengeId: String,
    val challenge: JsonElement
) {
    /**
     * Extracts the nested `publicKey` JSON string if wrapped inside `{ "publicKey": { ... } }`,
     * or returns the raw challenge JSON string suitable for passing into Android Credential Manager.
     */
    val publicKeyJson: String
        get() {
            val rootObj = when (challenge) {
                is JsonObject -> challenge
                is JsonPrimitive -> if (challenge.isString) {
                    try {
                        Json.parseToJsonElement(challenge.content) as? JsonObject
                    } catch (_: Exception) {
                        null
                    }
                } else null
                else -> null
            }
            val pk = rootObj?.get("publicKey")
            return pk?.toString()
                ?: rootObj?.toString()
                ?: (if (challenge is JsonPrimitive && challenge.isString) challenge.content else challenge.toString())
        }
}

/**
 * Request payload submitted to `POST /api/auth/passkey/login/finish`.
 *
 * Completes discoverable passkey authentication by submitting the authenticator assertion.
 *
 * @property challengeId Ephemeral challenge UUID issued during [PasskeyChallengeResponse].
 * @property credential The JSON-serialized WebAuthn public key assertion response produced by the authenticator.
 */
@Serializable
data class PasskeyLoginFinishRequest(
    @SerialName("challenge_id")
    val challengeId: String,
    val credential: JsonElement
)

/**
 * Request payload submitted to `POST /api/v1/auth/passkey/register/finish`.
 *
 * Completes passkey registration by submitting the authenticator attestation and client-encrypted device label.
 *
 * @property challengeId Ephemeral challenge UUID issued during [PasskeyChallengeResponse].
 * @property credential The JSON-serialized WebAuthn attestation response produced by the authenticator.
 * @property encryptedMetadata Hex-encoded ciphertext containing the client-encrypted device nickname (up to 2048 hex chars).
 */
@Serializable
data class PasskeyRegisterFinishRequest(
    @SerialName("challenge_id")
    val challengeId: String,
    val credential: JsonElement,
    @SerialName("encrypted_metadata")
    val encryptedMetadata: String = ""
)

/**
 * Metadata record representing an enrolled passkey returned by `GET /api/v1/auth/passkey`.
 *
 * @property credentialId Hex-encoded credential identifier.
 * @property encryptedMetadata Hex-encoded ciphertext containing the client-encrypted device nickname.
 * @property createdAt Unix timestamp (seconds) when the passkey was enrolled.
 * @property lastUsed Unix timestamp (seconds) when the passkey was last used for authentication, or 0 if never used.
 */
@Serializable
data class PasskeyMetadataRow(
    @SerialName("credential_id")
    val credentialId: String,
    @SerialName("encrypted_metadata")
    val encryptedMetadata: String = "",
    @SerialName("created_at")
    val createdAt: Long = 0L,
    @SerialName("last_used")
    val lastUsed: Long = 0L
) {
    /**
     * Indicates whether this passkey has completed at least one successful authentication ceremony.
     */
    val hasBeenUsed: Boolean
        get() = lastUsed > 0L
}

/**
 * Alias for [PasskeyMetadataRow] matching backend model terminology.
 */
typealias PasskeySummary = PasskeyMetadataRow
